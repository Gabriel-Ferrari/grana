/** Palpite de ícone pelo nome (o usuário pode trocar em Ajustes). */
const GUESS: [RegExp, string][] = [
    [/bar|restaurante|lanche|delivery|ifood/, 'restaurant'],
    [/alimenta|comida/, 'lunch_dining'],
    [/caf[eé]/, 'local_cafe'],
    [/mercado|supermercado/, 'shopping_cart'],
    [/roupa|vestu/, 'checkroom'],
    [/compra/, 'shopping_bag'],
    [/casa|moradia|aluguel/, 'home'],
    [/energia|luz/, 'bolt'],
    [/[aá]gua/, 'water_drop'],
    [/internet|claro|vivo|tim|telefone|celular/, 'smartphone'],
    [/carro|ve[ií]culo/, 'directions_car'],
    [/combust|gasolina|posto/, 'local_gas_station'],
    [/transporte|[oô]nibus|uber|99/, 'directions_bus'],
    [/viagem|viagens/, 'flight'],
    [/sa[uú]de|m[eé]dic/, 'health_and_safety'],
    [/farm[aá]cia|rem[eé]dio/, 'local_pharmacy'],
    [/academia|gym|esporte/, 'fitness_center'],
    [/cuidado|beleza|est[eé]tica/, 'spa'],
    [/pet/, 'pets'],
    [/fam[ií]lia|filho/, 'family_restroom'],
    [/educa|escola|curso|faculdade/, 'school'],
    [/assinatura|servi[cç]o|streaming/, 'subscriptions'],
    [/lazer|hobb|jogo/, 'sports_esports'],
    [/festa|balada/, 'celebration'],
    [/presente|doa[cç]/, 'redeem'],
    [/imposto|taxa|tarifa/, 'receipt_long'],
    [/pagamento de fatura|fatura|cart[aã]o/, 'credit_card'],
    [/d[ií]vida|empr[eé]stimo|financiamento/, 'account_balance'],
    [/investimento|rendimento/, 'trending_up'],
    [/sal[aá]rio|trabalho/, 'work'],
    [/receita|renda|freela/, 'payments'],
];
export function guessIcon(name: string): string {
    const n = name.toLowerCase();
    return GUESS.find(([re]) => re.test(n))?.[1] ?? 'category';
}

/** Carrega só os glifos usados (Google Fonts icon_names exige ordem alfabética). */
export function loadSymbols() {
    const names = [...new Set([...UI, ...CATEGORY_ICONS, ...GUESS.map(([, i]) => i)])].sort().join(',');
    const link = document.createElement('link');
    link.rel = 'stylesheet';
    link.href = `https://fonts.googleapis.com/css2?family=Material+Symbols+Rounded:opsz,wght,FILL,GRAD@20..48,300..600,0..1,0&icon_names=${names}&display=block`;
    document.head.append(link);
}

