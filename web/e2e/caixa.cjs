const { chromium } = require('playwright');
const URL = process.env.TARGET_URL || 'http://localhost:4200', OUT = process.env.OUT_DIR;
const ok = (n, c, x = '') => console.log(`${c ? '✅' : '❌'} ${n}${x ? ' — ' + x : ''}`);
(async () => {
  const b = await chromium.launch({ headless: true });
  const page = await b.newPage({ viewport: { width: 1440, height: 900 } });
  const errs = []; page.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
  await page.goto(URL);
  await page.getByLabel('E-mail').fill(process.env.TEST_EMAIL);
  await page.getByLabel('Senha', { exact: true }).fill(process.env.TEST_PASSWORD);
  await page.getByRole('button', { name: /^Entrar$/ }).click();
  await page.waitForTimeout(2500);
  await page.goto(URL + '/lancamentos?m=2026-11'); await page.waitForTimeout(2000);
  const nAll = await page.locator('.item').count();
  const cardRows = await page.locator('.item .sub:has-text("credit_card")').count();
  await page.getByRole('button', { name: 'Caixa' }).click(); await page.waitForTimeout(800);
  const nCash = await page.locator('.item').count();
  const inv = await page.locator('.item:has-text("Fatura a pagar")').count();
  ok('modo caixa troca lista', nAll !== nCash, `tudo ${nAll} (cartão ${cardRows}) → caixa ${nCash}`);
  ok('faturas em aberto como linha', inv > 0, `${inv} faturas`);
  const strip = await page.locator('.sum-strip').innerText();
  ok('rodapé saldo/previsto', /Saldo hoje/.test(strip) && /Previsto em/.test(strip), strip.replace(/\n/g, ' | '));
  await page.screenshot({ path: `${OUT}/caixa.png` });
  if (inv) { await page.locator('.item:has-text("Fatura a pagar")').first().click(); await page.waitForTimeout(800); ok('fatura abre cartões', page.url().includes('/cartoes?c='), page.url()); }
  await page.goto(URL + '/lancamentos?m=2026-11'); await page.waitForTimeout(1500);
  ok('modo caixa persiste', await page.locator('.chips-row .seg button.on').innerText() === 'Caixa');
  await page.getByRole('button', { name: 'Tudo' }).click();
  await page.locator('g-chip-select:has-text("Tipo") button').first().click(); await page.waitForTimeout(300);
  await page.getByText('Parcelados', { exact: true }).click(); await page.waitForTimeout(500);
  const parc = await page.locator('.item').count(), parcTag = await page.locator('.item .tag:text-matches("^\\\\d+/\\\\d+$")').count();
  ok('filtro parcelados', parc > 0 && parc === parcTag, `${parc} itens, ${parcTag} com n/m`);
  await page.keyboard.press('Escape');
  await page.locator('.item').first().click(); await page.waitForTimeout(800);
  const desc = await page.locator('.drawer input[name=d]').inputValue();
  await page.getByRole('button', { name: 'Duplicar' }).click(); await page.waitForTimeout(800);
  const t = await page.locator('.drawer').innerText();
  ok('duplicar abre novo', (await page.locator('.drawer input[name=d]').inputValue()) === desc, desc);
  await page.screenshot({ path: `${OUT}/duplicar.png` });
  console.log('erros console:', errs);
  await b.close();
})();
