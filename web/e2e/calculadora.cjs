const { chromium } = require('playwright');
const URL = process.env.TARGET_URL || 'http://localhost:4200', OUT = process.env.OUT_DIR;
const ok = (n, c, x = '') => console.log(`${c ? '✅' : '❌'} ${n}${x ? ' — ' + x : ''}`);
(async () => {
  const b = await chromium.launch({ headless: true });
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const page = await ctx.newPage();
  const errs = []; page.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
  await page.goto(URL);
  await page.getByLabel('E-mail').fill(process.env.TEST_EMAIL);
  await page.getByLabel('Senha', { exact: true }).fill(process.env.TEST_PASSWORD);
  await page.getByRole('button', { name: /^Entrar$/ }).click();
  await page.waitForTimeout(2500);
  await page.locator('.tab-add').click(); await page.waitForTimeout(800);
  const k = (t) => page.locator('.keypad button', { hasText: new RegExp(`^${t}$`) }).first().click();
  const val = async () => (await page.locator('#valor').inputValue()).replace(/\s/g, ' ');
  for (const d of '1200') await k(d);
  await page.getByRole('button', { name: 'Somar' }).click(); await page.waitForTimeout(150);
  const expr1 = await page.locator('.calc-expr').innerText();
  for (const d of '500') await k(d);
  await page.screenshot({ path: `${OUT}/calc-m.png` });
  await page.getByRole('button', { name: 'Subtrair' }).click(); await page.waitForTimeout(150);
  const expr2 = await page.locator('.calc-expr').innerText();
  for (const d of '200') await k(d);
  await page.getByRole('button', { name: 'Igual' }).click(); await page.waitForTimeout(150);
  ok('12 + 5 − 2 = 15', (await val()) === 'R$ 15,00', `${expr1} → ${expr2} → ${await val()}`);
  ok('expressão some após =', !(await page.locator('.calc-expr').count()));
  await page.getByRole('button', { name: 'Somar' }).click(); for (const d of '100') await k(d);
  await page.getByRole('button', { name: 'Pronto' }).click(); await page.waitForTimeout(200);
  ok('Pronto resolve pendente', (await val()) === 'R$ 16,00', await val());
  await page.locator('.tx-amount').click(); await page.waitForTimeout(300);
  await page.getByRole('button', { name: 'Zerar' }).click(); await page.waitForTimeout(150);
  ok('C zera', (await val()) === 'R$ 0,00', await val());
  const bb = await page.locator('.keypad').boundingBox();
  ok('teclado 4 colunas cabe na tela', bb.x >= 0 && bb.x + bb.width <= 390, `${Math.round(bb.x)}..${Math.round(bb.x + bb.width)}`);
  await ctx.close();
  // desktop: digitando
  const p2 = await b.newPage({ viewport: { width: 1440, height: 900 } });
  await p2.goto(URL);
  await p2.getByLabel('E-mail').fill(process.env.TEST_EMAIL);
  await p2.getByLabel('Senha', { exact: true }).fill(process.env.TEST_PASSWORD);
  await p2.getByRole('button', { name: /^Entrar$/ }).click();
  await p2.waitForTimeout(2500);
  await p2.keyboard.press('d'); await p2.waitForTimeout(800);
  await p2.locator('#valor').pressSequentially('1000+250-50=', { delay: 30 });
  ok('desktop: 10 + 2,50 − 0,50 = 12', (await p2.locator('#valor').inputValue()).replace(/\s/g, ' ') === 'R$ 12,00', await p2.locator('#valor').inputValue());
  console.log('erros console:', errs);
  await b.close();
})();
